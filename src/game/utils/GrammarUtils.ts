export function mapGrammarType(type?: string): string {
    if (!type) return '-';

    const map: Record<string, string> = {
        '语素': '语素 (Hình vị)',
        '词类': '词类 (Loại từ)',
        '短语': '短语 (Cụm từ)',
        '句子成分': '句子成分 (Thành phần câu)',
        '句子的类型': '句子的类型 (Loại câu)',
        '动作的态': '动作的态 (Thể của hành động)',
        '特殊表达法': '特殊表达法 (Cách biểu đạt đặc biệt)',
        '固定格式': '固定格式 (Cấu trúc cố định)',
        '语段（句群）': '语段（句群） (Đoạn câu)',
    };

    return type
        .split(/[,，、]/)
        .map(item => {
            const key = item.trim();
            return map[key] ?? key;
        })
        .join(' / ');
}


